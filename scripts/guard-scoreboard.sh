#!/usr/bin/env bash
# Guard scoreboard (#363, #364). docs/guard/scoreboard.md and the generated
# section of docs/benchmarks/M18-guard.md are rendered from the archived
# reports in docs/guard/results/ and never edited by hand.
#
#   scripts/guard-scoreboard.sh                  rewrite both from the archive
#   scripts/guard-scoreboard.sh --check [FRESH...]
#       fail if either differs from a fresh rendering of the archive; with
#       FRESH report files, also fail if their deterministic facts (verdict
#       counts, E1 cells, E2 counts, E4a decisions; not timings) differ from
#       the archive's
set -euo pipefail
cd "$(dirname "$0")/.."

results=docs/guard/results
doc=docs/guard/scoreboard.md
report=docs/benchmarks/M18-guard.md
begin='<!-- BEGIN GENERATED by scripts/guard-scoreboard.sh from docs/guard/results/; do not edit -->'
end='<!-- END GENERATED -->'
crom=(cargo run --quiet --locked -p crom-cli --)

render() {
  "${crom[@]}" eval scoreboard --guard-report "$results" --format md
}

# $report with everything between the markers replaced by the rendering
# (file $1) minus its title line.
splice() {
  local n
  n=$(grep -cxF "$begin" "$report" || true)
  [[ "$n" == 1 && $(grep -cxF "$end" "$report" || true) == 1 ]] || {
    echo "error: $report needs exactly one '$begin' and one '$end' line" >&2
    return 1
  }
  awk -v begin="$begin" -v end="$end" -v gen="$1" '
    $0 == begin { print; first = 1
                  while ((getline line < gen) > 0) { if (first) { first = 0; continue } print line }
                  skip = 1; next }
    $0 == end { skip = 0 }
    !skip { print }
  ' "$report"
}

rendered=$(mktemp)
trap 'rm -f "$rendered"' EXIT
render >"$rendered"

if [[ "${1:-}" == "--check" ]]; then
  shift
  if ! diff -u "$doc" "$rendered"; then
    echo "error: $doc is stale; run scripts/guard-scoreboard.sh" >&2
    exit 1
  fi
  if ! diff -u "$report" <(splice "$rendered"); then
    echo "error: the generated section of $report is stale; run scripts/guard-scoreboard.sh" >&2
    exit 1
  fi
  echo "ok: $doc and $report match $results"
  if (($#)); then
    args=()
    for f in "$@"; do
      args+=(--guard-report "$f")
    done
    "${crom[@]}" eval scoreboard "${args[@]}" --guard-check "$results"
  fi
else
  cp "$rendered" "$doc"
  spliced=$(splice "$rendered")
  printf '%s\n' "$spliced" >"$report"
  echo "wrote $doc and the generated section of $report"
fi
